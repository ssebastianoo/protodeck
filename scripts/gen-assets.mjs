// Embeds every runtime asset (Tailwind, font, UI files, skill, templates) into
// src/assets.generated.ts so the package needs no file lookups at runtime.
// The same module works for the npm build and for `bun build --compile`.
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(root, "package.json"));
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

const text = {};
const binary = {};

text["tailwind.js"] = readFileSync(require.resolve("@tailwindcss/browser"), "utf8");
const fontDir = join(dirname(require.resolve("@fontsource-variable/inter/package.json")), "files");
binary["inter-latin.woff2"] = readFileSync(join(fontDir, "inter-latin-wght-normal.woff2")).toString("base64");
binary["inter-latin-ext.woff2"] = readFileSync(join(fontDir, "inter-latin-ext-wght-normal.woff2")).toString("base64");

for (const f of readdirSync(join(root, "ui"))) text[f] = readFileSync(join(root, "ui", f), "utf8");
text["SKILL.md"] = readFileSync(join(root, "skill", "SKILL.md"), "utf8");

const templates = {};
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else templates[relative(join(root, "templates"), p).split("\\").join("/")] = readFileSync(p, "utf8");
  }
})(join(root, "templates"));

const out =
  "// Generated by scripts/gen-assets.mjs. Do not edit.\n" +
  `export const VERSION = ${JSON.stringify(pkg.version)};\n` +
  `export const TEXT: Record<string, string> = ${JSON.stringify(text)};\n` +
  `export const BINARY: Record<string, string> = ${JSON.stringify(binary)};\n` +
  `export const TEMPLATES: Record<string, string> = ${JSON.stringify(templates)};\n`;
writeFileSync(join(root, "src", "assets.generated.ts"), out);
console.log(`assets: ${Object.keys(text).length} text, ${Object.keys(binary).length} binary, ${Object.keys(templates).length} templates`);
